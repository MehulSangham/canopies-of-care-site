export type NodeKind = 'claim' | 'frame' | 'metaphor';
export type NodeStance = 'reframe' | 'dominant' | 'catalytic';
export type AttachmentRole =
  | 'advances-reframe'
  | 'describes-dominant'
  | 'aims-catalytic';

export const NODE_KINDS: NodeKind[] = ['claim', 'frame', 'metaphor'];
export const NODE_STANCES: NodeStance[] = ['reframe', 'dominant', 'catalytic'];
export const ATTACHMENT_ROLES: { id: AttachmentRole; label: string }[] = [
  { id: 'advances-reframe', label: 'Advances the reframe' },
  { id: 'describes-dominant', label: 'Describes the dominant account' },
  { id: 'aims-catalytic', label: 'Aims at a catalytic community' },
];

export interface ClaimArgument {
  grounds?: string[];
  /** Source ids backing each ground, index-aligned with `grounds` */
  groundSources?: string[][];
  warrant?: string;
  qualifier?: string;
  rebuttal?: string;
  answer?: string;
}

export type SourceType = 'primary' | 'scholarship' | 'journalism' | 'reference';

export const SOURCE_TYPES: SourceType[] = [
  'primary',
  'scholarship',
  'journalism',
  'reference',
];

export interface SourceRecord {
  id: string;
  /** Full citation line (markdown-ish: *italics*, may end with a URL) */
  citation: string;
  url?: string;
  type?: SourceType;
  /** Where it is cited (regenerated by the sources build script) */
  citedBy?: { slug: string; footnoteId: string }[];
}

/** Stable id from a citation line: first author/institution + year-ish stem. */
export function slugifySourceId(citation: string): string {
  const stem = citation
    .replace(/https?:\/\/\S+/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .split('-')
    .slice(0, 6)
    .join('-');
  return `src-${stem || 'untitled'}`;
}

export function searchSources(sources: SourceRecord[], query: string): SourceRecord[] {
  const q = query.trim().toLowerCase();
  if (!q) return sources;
  return sources.filter(
    (s) =>
      s.id.toLowerCase().includes(q) ||
      s.citation.toLowerCase().includes(q) ||
      (s.type ?? '').includes(q),
  );
}

